CREATE TABLE IF NOT EXISTS `documents` (
  `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
  `document_code` VARCHAR(100) DEFAULT NULL,
  `document_number` VARCHAR(100) DEFAULT NULL,
  `title` VARCHAR(255) NOT NULL,
  `document_type` VARCHAR(40) NOT NULL,
  `template_code` VARCHAR(50) DEFAULT NULL,
  `request_id` BIGINT DEFAULT NULL,
  `employee_id` INT DEFAULT NULL,
  `department_id` INT DEFAULT NULL,
  `employee_code_snapshot` VARCHAR(50) DEFAULT NULL,
  `employee_name_snapshot` VARCHAR(255) DEFAULT NULL,
  `department_name_snapshot` VARCHAR(255) DEFAULT NULL,
  `owner_user_id` INT NOT NULL,
  `owner_role_id` VARCHAR(30) DEFAULT NULL,
  `created_by` INT NOT NULL,
  `updated_by` INT DEFAULT NULL,
  `visibility` VARCHAR(20) NOT NULL DEFAULT 'PRIVATE',
  `allowed_roles` VARCHAR(500) DEFAULT NULL,
  `can_edit_roles` VARCHAR(500) DEFAULT NULL,
  `can_export_roles` VARCHAR(500) DEFAULT NULL,
  `status` VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
  `page_size` VARCHAR(10) NOT NULL DEFAULT 'A4',
  `margin_top` INT NOT NULL DEFAULT 20,
  `margin_right` INT NOT NULL DEFAULT 18,
  `margin_bottom` INT NOT NULL DEFAULT 20,
  `margin_left` INT NOT NULL DEFAULT 18,
  `current_version_id` BIGINT DEFAULT NULL,
  `archived_at` DATETIME DEFAULT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY `uk_doc_code` (`document_code`),
  INDEX `idx_doc_number` (`document_number`),
  INDEX `idx_doc_request` (`request_id`),
  INDEX `idx_doc_employee` (`employee_id`, `status`),
  INDEX `idx_doc_department` (`department_id`, `status`),
  INDEX `idx_doc_owner` (`owner_user_id`, `status`),
  INDEX `idx_doc_status_created` (`status`, `created_at`),
  INDEX `idx_doc_current_version` (`current_version_id`),
  CONSTRAINT `fk_doc_request` FOREIGN KEY (`request_id`) REFERENCES `employee_requests` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_doc_employee` FOREIGN KEY (`employee_id`) REFERENCES `employees` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_doc_department` FOREIGN KEY (`department_id`) REFERENCES `departments` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_doc_owner` FOREIGN KEY (`owner_user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_doc_created_by` FOREIGN KEY (`created_by`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_doc_updated_by` FOREIGN KEY (`updated_by`) REFERENCES `users` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `document_versions` (
  `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
  `document_id` BIGINT NOT NULL,
  `version_number` INT NOT NULL,
  `title` VARCHAR(255) NOT NULL,
  `document_number` VARCHAR(100) DEFAULT NULL,
  `template_code` VARCHAR(50) DEFAULT NULL,
  `page_size` VARCHAR(10) NOT NULL DEFAULT 'A4',
  `margin_top` INT NOT NULL DEFAULT 20,
  `margin_right` INT NOT NULL DEFAULT 18,
  `margin_bottom` INT NOT NULL DEFAULT 20,
  `margin_left` INT NOT NULL DEFAULT 18,
  `content_json` LONGTEXT NOT NULL,
  `content_html` LONGTEXT DEFAULT NULL,
  `change_note` VARCHAR(500) DEFAULT NULL,
  `editor_user_id` INT NOT NULL,
  `editor_name_snapshot` VARCHAR(255) DEFAULT NULL,
  `restored_from_version_id` BIGINT DEFAULT NULL,
  `edited_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY `uk_dv_document_version` (`document_id`, `version_number`),
  INDEX `idx_dv_document_edited` (`document_id`, `edited_at`),
  INDEX `idx_dv_editor` (`editor_user_id`, `edited_at`),
  INDEX `idx_dv_restored_from` (`restored_from_version_id`),
  CONSTRAINT `fk_dv_document` FOREIGN KEY (`document_id`) REFERENCES `documents` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_dv_editor` FOREIGN KEY (`editor_user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `document_files` (
  `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
  `document_id` BIGINT NOT NULL,
  `version_id` BIGINT DEFAULT NULL,
  `file_name` VARCHAR(255) NOT NULL,
  `file_format` VARCHAR(10) NOT NULL,
  `mime_type` VARCHAR(150) NOT NULL,
  `file_size` BIGINT NOT NULL DEFAULT 0,
  `file_data` LONGBLOB NOT NULL,
  `checksum_sha256` CHAR(64) DEFAULT NULL,
  `source` VARCHAR(20) NOT NULL DEFAULT 'EXPORT',
  `status` VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  `is_official` TINYINT(1) NOT NULL DEFAULT 1,
  `format_check_status` VARCHAR(20) NOT NULL DEFAULT 'NOT_CHECKED',
  `format_check_note` TEXT DEFAULT NULL,
  `format_checked_at` DATETIME DEFAULT NULL,
  `download_count` INT NOT NULL DEFAULT 0,
  `last_downloaded_at` DATETIME DEFAULT NULL,
  `uploaded_by` INT NOT NULL,
  `uploaded_by_name` VARCHAR(255) DEFAULT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_df_document` (`document_id`, `status`, `created_at`),
  INDEX `idx_df_document_format` (`document_id`, `file_format`, `status`),
  INDEX `idx_df_version` (`version_id`, `file_format`),
  INDEX `idx_df_uploaded_by` (`uploaded_by`, `created_at`),
  INDEX `idx_df_checksum` (`checksum_sha256`),
  CONSTRAINT `fk_df_document` FOREIGN KEY (`document_id`) REFERENCES `documents` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_df_version` FOREIGN KEY (`version_id`) REFERENCES `document_versions` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_df_uploaded_by` FOREIGN KEY (`uploaded_by`) REFERENCES `users` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

ALTER TABLE `document_versions`
  ADD CONSTRAINT `fk_dv_restored_from` FOREIGN KEY (`restored_from_version_id`) REFERENCES `document_versions` (`id`) ON DELETE SET NULL;

ALTER TABLE `documents`
  ADD CONSTRAINT `fk_doc_current_version` FOREIGN KEY (`current_version_id`) REFERENCES `document_versions` (`id`) ON DELETE SET NULL;
